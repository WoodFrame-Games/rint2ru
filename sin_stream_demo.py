"""Детерминированный генератор букв из математики (sin(x^2)).

Альтернативный источник «числового потока» для экспериментов rint2ru:
вместо случайных цифр — детерминированная последовательность, ключ = шаг.

Правила:
- x накапливается: x += step на каждом шаге;
- n = |int(sin(x^2) * 100)| mod 100  ->  число 0..99 (две цифры);
- n <= 33  ->  буква алфавита с номером n (1-based), 0 -> пробел;
- n > 33   ->  цифры числа складываются, пока не получится номер <= 33
  (для двузначных n одна свёртка всегда достаточна: 9+9=18);
- печатает 30 цифр и 15 букв. Одинаковый шаг -> одинаковый текст.

Ключевое отличие от основного конвейера rint2ru: здесь нет поиска и словаря —
это детерминированный адресуемый источник (ключ = шаг), а не случайный хаос.

Запуск:
    python3 sin_stream_demo.py
    Введите константу (шаг): 3.14
"""

import math

# Русский алфавит (33 буквы)
ALPHABET = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
N_LETTERS = len(ALPHABET)          # 33


def number_to_letter(n: int) -> str:
    """Переводит число в букву русского алфавита.

    Если число больше 33 — складываем цифры, пока не получим индекс буквы.
    """
    if n <= 0:
        return " "                 # 0 не имеет буквы — оставим пробел
    while n > N_LETTERS:
        n = sum(int(d) for d in str(n))
    return ALPHABET[n - 1]


def main() -> None:
    step = float(input("Введите константу (шаг): "))

    x = 0.0                        # текущее значение аргумента
    numbers: list[str] = []
    letters: list[str] = []

    # 15 итераций → 15 чисел по 2 цифры = 30 символов и 15 букв
    for _ in range(15):
        # 1) Прибавляем константу к числу предыдущего шага
        x += step

        # 2) Считаем sin(x²) и приводим к целому виду
        #    (масштаб *100 нужен, чтобы получить осмысленные цифры —
        #     сам sin лежит в диапазоне [-1, 1])
        value = math.sin(x * x) * 100

        # Отбрасываем дробную часть, затем всё, что больше десятков (mod 100)
        n = abs(int(value)) % 100

        # 3) Переводим число в букву
        numbers.append(f"{n:02d}")     # двузначный вид: 07, 42, 99 и т.д.
        letters.append(number_to_letter(n))

    # 4) Вывод в две строки
    print("".join(numbers)[:30])       # не более 30 символов
    print("".join(letters)[:15])       # не более 15 букв


if __name__ == "__main__":
    main()